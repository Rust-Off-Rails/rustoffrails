//! `generate channel <name>` (`rails generate channel`): a realtime topic `<name>:<id>` the server
//! pushes to (`broadcast`), its authorization (checked on every join and push), the arm in
//! `Channels::authorize`, and tests. When a scoped model of that name exists, only its owner may
//! join `<name>:<id>`; otherwise each person may join only their own `<name>:<their id>`.
//! Needs the realtime part. Spec: guides/channels.md.

use super::Flags;
use super::app::AppInfo;
use super::names::Names;
use super::plan::{Anchor, Plan};
use crate::util::{Fail, Result};

/// `generate channel <name>`.
pub fn plan(info: &AppInfo, args: &[String], flags: &Flags) -> Result<Plan> {
    if !info.realtime {
        return Err(Fail::usage(
            "generate channel needs the realtime part: cargo offrails add realtime",
        ));
    }
    let n = Names::plain(&args[0])?;
    let name = &n.singular;
    if ["room", "user", "identity", "accounts", "live_room"].contains(&name.as_str()) {
        return Err(Fail::usage(format!(
            "'{name}' is taken by the realtime part's own topics; pick another name"
        )));
    }
    let mut plan = Plan::new("channel", name, args);
    let model_src = info.model_source(name).map(|(_, t)| t);
    let by_model = match flags.recorded("by").as_deref() {
        Some(b) => b == "model",
        None => {
            info.auth
                && model_src
                    .as_deref()
                    .is_some_and(|s| s.contains("pub async fn find_for("))
        }
    };
    plan.option("by", if by_model { "model" } else { "person" });
    let k = &info.krate;
    let cmd = plan.command();
    let auth = if by_model {
        format!(
            "/// May `member` join `{name}:<id>`? Only the {lower}'s owner (against the database now).\npub async fn authorize(s: &AppState, member: &Member, id: &str) -> Result<(), Rejection> {{\n    let (Ok(person_id), Ok(id)) = (member.key.parse::<i64>(), id.parse::<i64>()) else {{\n        return Err(Rejection::forbidden());\n    }};\n    let user = match user::find_self(&s.db, person_id).await {{\n        Ok(u) => u,\n        Err(AppError::NotFound) => return Err(Rejection::forbidden()),\n        // Fails closed.\n        Err(_) => return Err(Rejection::unavailable()),\n    }};\n    match {name}::find_for(&s.db, &user, id).await {{\n        Ok(_) => Ok(()),\n        // SECURITY: someone else's id and a missing one get the same answer.\n        Err(AppError::NotFound) => Err(Rejection::forbidden()),\n        Err(_) => Err(Rejection::unavailable()),\n    }}\n}}\n",
            lower = n.lower
        )
    } else {
        format!(
            "/// May `member` join `{name}:<id>`? Only their own (`<id>` is their key).\n/// APP: widen it with a database check when others should see a topic.\npub async fn authorize(_s: &AppState, member: &Member, id: &str) -> Result<(), Rejection> {{\n    // SECURITY: exact match only; deny by default.\n    if id == member.key {{\n        Ok(())\n    }} else {{\n        Err(Rejection::forbidden())\n    }}\n}}\n"
        )
    };
    let imports = if by_model {
        format!(
            "use crate::error::AppError;\nuse crate::kernel::hub::{{Member, Payload, Rejection}};\nuse crate::models::{{{name}, user}};\nuse crate::state::AppState;\n"
        )
    } else {
        "use crate::kernel::hub::{Member, Payload, Rejection};\nuse crate::state::AppState;\n"
            .to_owned()
    };
    plan.create(
        format!("src/channels/{name}.rs"),
        format!(
            "//! `{name}:<id>`: the server pushes changes to the pages watching one {lower}.\n//! Generated by `{cmd}`. GUIDE: .offrails/guides/channels.md#the-app-side\n//! Send after the commit: `channels::{name}::broadcast(&s, id, \"updated\", &json!({{…}}))`.\n\n{imports}\npub const PREFIX: &str = \"{name}\";\n\npub fn topic(id: i64) -> String {{\n    format!(\"{{PREFIX}}:{{id}}\")\n}}\n\n{auth}\n/// Pushes `event` to everyone on `{name}:<id>` (every node). Returns local deliveries.\npub fn broadcast(s: &AppState, id: i64, event: &str, data: &Payload) -> usize {{\n    s.hub.broadcast(&topic(id), None, event, data)\n}}\n",
            lower = n.lower
        ),
    );
    plan.insert(
        "src/channels/mod.rs",
        "channel mods",
        format!("pub mod {name};\n"),
    );
    plan.insert_at(
        "src/channels/mod.rs",
        Anchor::Before {
            after: Some("async fn authorize".into()),
            pattern: "Some((\"user\", id)) if id == member.key".into(),
        },
        format!("Some((\"{name}\", id)) => {name}::authorize(self, member, id).await,\n"),
    );
    let member = "fn member(key: &str) -> Member {\n    Member {\n        key: key.to_owned(),\n        meta: serde_json::json!({}),\n        session: None,\n    }\n}\n\n";
    let body = if by_model {
        format!(
            "#[tokio::test]\nasync fn only_the_owner_may_join() {{\n    let app = TestApp::new().await;\n    let alice = factories::user(app.db(), \"alice@example.com\").await;\n    let bob = factories::user(app.db(), \"bob@example.com\").await;\n    let record = factories::{name}(app.db(), &alice).await;\n    let id = record.id.to_string();\n    assert!({name}::authorize(&app.state, &member(&alice.id.to_string()), &id).await.is_ok());\n    assert!({name}::authorize(&app.state, &member(&bob.id.to_string()), &id).await.is_err());\n    assert!({name}::authorize(&app.state, &member(&alice.id.to_string()), \"999999\").await.is_err());\n    assert!({name}::authorize(&app.state, &member(\"not-an-id\"), &id).await.is_err());\n}}\n"
        )
    } else {
        format!(
            "#[tokio::test]\nasync fn a_person_may_join_only_their_own_topic() {{\n    let app = TestApp::new().await;\n    assert!({name}::authorize(&app.state, &member(\"7\"), \"7\").await.is_ok());\n    assert!({name}::authorize(&app.state, &member(\"7\"), \"8\").await.is_err());\n}}\n"
        )
    };
    let uses = if by_model {
        "use crate::factories;\nuse crate::support::TestApp;\n"
    } else {
        "use crate::support::TestApp;\n"
    };
    plan.create(
        format!("tests/app/{name}_channel_test.rs"),
        format!(
            "//! The `{name}:<id>` topic (src/channels/{name}.rs). Generated by `{cmd}`.\n//! SECURITY: joining someone else's topic is refused (test-standards.md, Realtime).\n\nuse {k}::channels::{name};\nuse {k}::kernel::hub::Member;\n\n{uses}\n{member}{body}\n#[test]\nfn topics_are_prefixed() {{\n    assert_eq!({name}::topic(42), \"{name}:42\");\n}}\n"
        ),
    );
    plan.insert(
        "tests/app/main.rs",
        "test mods",
        format!("mod {name}_channel_test;\n"),
    );
    plan.next.push(format!(
        "broadcast after each change commits (channels::{name}::broadcast), and subscribe the page to `{name}:<id>` (static/channels.js; guides/channels.md#client-side)"
    ));
    Ok(plan)
}
