/// Up to four columns for the index table (besides the name): no long text or JSON.
fn index_columns(fields: &[Field]) -> Vec<&Field> {
    let label = model::label_field(fields).map(|f| f.name.clone());
    fields
        .iter()
        .filter(|f| Some(&f.name) != label.as_ref())
        .filter(|f| !matches!(f.kind, Kind::Text | Kind::Json))
        .take(4)
        .collect()
}

/// A field to break and how: (field, input, message). `None` when nothing can fail.
fn invalid_case(fields: &[Field]) -> Option<(&Field, &'static str, &'static str)> {
    if let Some(f) = fields
        .iter()
        .find(|f| !f.nullable && matches!(f.kind, Kind::String | Kind::Text))
    {
        return Some((f, "", "can't be blank"));
    }
    if let Some(f) = fields
        .iter()
        .find(|f| !f.nullable && !matches!(f.kind, Kind::Boolean | Kind::References { .. }))
    {
        return Some((f, "", "can't be blank"));
    }
    fields.iter().find_map(|f| match f.kind {
        Kind::Integer | Kind::BigInt => Some((f, "twelve", "is not a number")),
        Kind::Date => Some((f, "someday", "is not a date")),
        Kind::DateTime => Some((f, "someday", "is not a date and time")),
        _ => None,
    })
}

/// The display string of a saved value (`r` is the model).
fn display(f: &Field, singular: &str) -> String {
    let c = f.column();
    let none = "\"—\".to_owned()";
    let fmt = |v: &str| -> String {
        match &f.kind {
            Kind::Money => format!("{singular}::money_to_string({v})"),
            Kind::Decimal { scale, .. } => format!("{v}.round_dp({scale}).to_string()"),
            Kind::DateTime => format!("{v}.format(\"%Y-%m-%d %H:%M UTC\").to_string()"),
            Kind::Date => format!("{v}.format(\"%Y-%m-%d\").to_string()"),
            Kind::References { target } => format!("format!(\"{} #{{}}\", {v})", target.human),
            _ => format!("{v}.to_string()"),
        }
    };
    match &f.kind {
        Kind::String | Kind::Text if f.nullable => {
            format!("r.{c}.clone().unwrap_or_else(|| {none})")
        }
        Kind::String | Kind::Text => format!("r.{c}.clone()"),
        Kind::Boolean if f.nullable => format!(
            "match r.{c} {{\n                Some(true) => \"Yes\".to_owned(),\n                Some(false) => \"No\".to_owned(),\n                None => {none},\n            }}"
        ),
        Kind::Boolean => format!("if r.{c} {{ \"Yes\".to_owned() }} else {{ \"No\".to_owned() }}"),
        Kind::Money if f.nullable => format!(
            "r.{c}.as_ref().map(|v| {}).unwrap_or_else(|| {none})",
            fmt("*v")
        ),
        _ if f.nullable => format!(
            "r.{c}.as_ref().map(|v| {}).unwrap_or_else(|| {none})",
            fmt("v")
        ),
        _ => fmt(&format!("r.{c}")),
    }
}

