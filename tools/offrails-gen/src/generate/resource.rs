    fn views(&self) -> String {
        let n = &self.spec.names;
        let (s, p, m, pc) = (&n.singular, &n.plural, &n.model, &n.plural_camel);
        let k = &self.info.krate;
        let _ = k;
        let mut out = format!(
            "//! Page structs for {lower}. Display values are computed here from loaded rows; no\n//! database access (.offrails/structure.md). Generated by `{cmd}`.\n\nuse askama::Template;\n\nuse super::Ctx;\nuse crate::models::{{Errors, {s}}};\nuse crate::routes::paths;\n\n",
            lower = n.lower_plural,
            cmd = self.spec.command
        );
        out.push_str(&format!(
            "/// One {lower} as pages show it: every value a display string.\n/// APP: times are shown in UTC; convert to the reader's zone here when the app knows it.\n#[derive(Debug, Clone)]\npub struct {m}View {{\n    pub id: i64,\n    pub label: String,\n",
            lower = n.lower
        ));
        for f in &self.spec.fields {
            out.push_str(&format!("    pub {}: String,\n", f.column()));
        }
        out.push_str("}\n\n");
        out.push_str(&format!(
            "impl {m}View {{\n    pub fn from_model(r: &{s}::Model) -> Self {{\n        Self {{\n            id: r.id,\n            label: r.label(),\n"
        ));
        for f in &self.spec.fields {
            out.push_str(&format!("            {}: {},\n", f.column(), display(f, s)));
        }
        out.push_str("        }\n    }\n}\n\n");
        out.push_str(&format!(
            "/// `GET /{kb}`\n#[derive(Template)]\n#[template(path = \"{p}/index.html\")]\npub struct {pc}Index {{\n    pub ctx: Ctx,\n    pub {p}: Vec<{m}View>,\n    pub page: u64,\n    pub more: bool,\n}}\n\nimpl {pc}Index {{\n    /// The pagination component's page count: this one, and the next when the query found more\n    /// (no COUNT query).\n    pub fn pages(&self) -> u64 {{\n        self.page + u64::from(self.more)\n    }}\n\n    /// Where its links go (`{{base}}page=n`).\n    pub fn page_base(&self) -> String {{\n        format!(\"{{}}?\", paths::{p}())\n    }}\n}}\n\n",
            kb = n.kebab
        ));
        out.push_str(&format!(
            "/// `GET /{kb}/{{id}}`\n#[derive(Template)]\n#[template(path = \"{p}/show.html\")]\npub struct {pc}Show {{\n    pub ctx: Ctx,\n    pub {s}: {m}View,\n}}\n\n",
            kb = n.kebab
        ));
        let choices_field = if self.has_choices() {
            format!("    pub choices: {m}Choices,\n")
        } else {
            String::new()
        };
        out.push_str(&format!(
            "/// `GET /{kb}/new`, and a failed create (422).\n#[derive(Template)]\n#[template(path = \"{p}/new.html\")]\npub struct {pc}New {{\n    pub ctx: Ctx,\n    pub params: {s}::{m}Params,\n    pub errors: Errors,\n    pub action: String,\n{choices_field}}}\n\n/// `GET /{kb}/{{id}}/edit`, and a failed update (422).\n#[derive(Template)]\n#[template(path = \"{p}/edit.html\")]\npub struct {pc}Edit {{\n    pub ctx: Ctx,\n    pub id: i64,\n    pub params: {s}::{m}Params,\n    pub errors: Errors,\n    pub action: String,\n{choices_field}}}\n",
            kb = n.kebab
        ));
        if self.has_choices() {
            out.push_str(&format!(
                "\n/// The form's `<select>` options: (id, label).\n#[derive(Debug, Clone, Default)]\npub struct {m}Choices {{\n"
            ));
            for (f, c) in self.refs() {
                if c {
                    out.push_str(&format!("    pub {}: Vec<(i64, String)>,\n", f.name));
                }
            }
            out.push_str("}\n");
        }
        out
    }

    // ---------- templates: the markup is files/html/resource.html ----------

    fn names_vars(&self) -> Vec<(&'static str, String)> {
        let n = &self.spec.names;
        vec![
            ("HP", n.human_plural.clone()),
            ("LOWER_P", n.lower_plural.clone()),
            ("LOWER", n.lower.clone()),
            ("S", n.singular.clone()),
            ("P", n.plural.clone()),
            ("LAYOUT", self.layout.clone()),
        ]
    }

    fn page(&self, name: &str, more: &[(&'static str, String)]) -> String {
        let mut vars = more.to_vec();
        vars.extend(self.names_vars());
        let refs: Vec<(&str, &str)> = vars.iter().map(|(k, v)| (*k, v.as_str())).collect();
        html::resource(name, &refs)
    }

    fn index_html(&self) -> String {
        let s = &self.spec.names.singular;
        let mut columns = vec![html::resource_inline("index column", &[("LABEL", "Name")])];
        let mut cells = html::resource("index label td", &[("S", s)]);
        for f in index_columns(&self.spec.fields) {
            columns.push(html::resource_inline(
                "index column",
                &[("LABEL", &f.human())],
            ));
            cells.push_str(&html::resource(
                "index td",
                &[("S", s), ("COL", &f.column())],
            ));
        }
        self.page(
            "index",
            &[("COLUMNS", columns.join(", ")), ("CELLS", cells)],
        )
    }

    fn show_html(&self) -> String {
        let s = &self.spec.names.singular;
        let mut rows = String::new();
        for f in &self.spec.fields {
            let pre = if matches!(f.kind, Kind::Text | Kind::Json) {
                html::resource_inline("show pre", &[])
            } else {
                String::new()
            };
            rows.push_str(&html::resource(
                "show row",
                &[
                    ("LABEL", &f.human()),
                    ("S", s),
                    ("COL", &f.column()),
                    ("PRE", &pre),
                ],
            ));
        }
        self.page("show", &[("ROWS", rows)])
    }

    fn form_html(&self) -> String {
        let fields: String = self
            .spec
            .fields
            .iter()
            .map(|f| self.form_field(f))
            .collect();
        self.page("form", &[("FIELDS", fields)])
    }

    fn form_field(&self, f: &Field) -> String {
        let required = if f.nullable || f.kind == Kind::Boolean {
            String::new()
        } else {
            html::resource_inline("required", &[])
        };
        let section = match &f.kind {
            Kind::String => "control string",
            Kind::Text => "control text",
            Kind::Integer | Kind::BigInt => "control integer",
            Kind::Decimal { .. } => "control decimal",
            Kind::Money => "control money",
            Kind::DateTime => "control datetime",
            Kind::Date => "control date",
            Kind::Uuid => "control uuid",
            Kind::Json => "control json",
            Kind::Boolean if !f.nullable => "control boolean",
            Kind::Boolean => "control optional boolean",
            Kind::References { .. } if self.spec.target(f).is_some_and(|t| t.choices) => {
                "control reference select"
            }
            Kind::References { .. } => "control reference id",
        };
        let target = match &f.kind {
            Kind::References { target } => target.lower.clone(),
            _ => String::new(),
        };
        html::resource(
            section,
            &[
                ("REQUIRED", &required),
                ("NAME", &f.param()),
                ("KEY", &f.name),
                ("LABEL", &f.human()),
                ("MAX", &model::max_len(f).to_string()),
                ("TARGET", &target),
            ],
        )
    }

