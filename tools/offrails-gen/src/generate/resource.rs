/// `generate resource <name> field:type…`.
pub fn plan(info: &AppInfo, args: &[String], flags: &Flags) -> Result<Plan> {
    info.require_htmx("generate resource")?;
    let name = super::names::Names::new(args.first().map(String::as_str).unwrap_or(""))?;
    if RESERVED.contains(&name.plural.as_str()) {
        return Err(Fail::usage(format!(
            "'{}' is a module every app already has; pick another name",
            name.plural
        )));
    }
    let mut plan = Plan::new("resource", &name.plural, args);
    let spec = ModelSpec::resolve(info, args, flags, &plan.command())?;
    let n = &spec.names;
    let fresh = flags.recorded("stamp").is_none();
    if fresh {
        feature::check_free(
            info,
            Some(&n.plural),
            &[
                n.plural.clone(),
                n.singular.clone(),
                format!("new_{}", n.singular),
                format!("edit_{}", n.singular),
                format!("delete_{}", n.singular),
            ],
            &[format!("/{}", n.kebab)],
        )?;
    }
    let stamp = flags
        .recorded("stamp")
        .unwrap_or_else(|| migration::stamp(info));
    plan.option("stamp", stamp.clone());
    plan.option("scope", spec.scope.as_str());
    let nav = !flags.no_nav && flags.recorded("nav").as_deref() != Some("no");
    plan.option("nav", if nav { "yes" } else { "no" });
    spec.plan_into(&mut plan, &stamp);

    let guard = info.exists("tests/app/guard_test.rs") || spec.scope == Scope::User;
    let layout = html::layout(info, flags, &mut plan)?;
    let ctx = Ctx {
        spec: &spec,
        info,
        guard,
        layout,
    };
    let (p, s) = (&n.plural, &n.singular);
    let c = format!("src/controllers/{p}");
    plan.create(format!("{c}/mod.rs"), ctx.controller_mod());
    plan.create(format!("{c}/index.rs"), ctx.controller_index());
    plan.create(format!("{c}/show.rs"), ctx.controller_show());
    plan.create(format!("{c}/new.rs"), ctx.controller_new());
    plan.create(format!("{c}/edit.rs"), ctx.controller_edit());
    plan.create(format!("{c}/destroy.rs"), ctx.controller_destroy());
    plan.insert(
        "src/controllers/mod.rs",
        "controller mods",
        format!("pub mod {p};\n"),
    );
    plan.create(format!("src/views/{p}.rs"), ctx.views());
    plan.insert("src/views/mod.rs", "view mods", format!("pub mod {p};\n"));
    plan.create(format!("templates/{p}/index.html"), ctx.index_html());
    plan.create(format!("templates/{p}/show.html"), ctx.show_html());
    plan.create(format!("templates/{p}/new.html"), ctx.new_html());
    plan.create(format!("templates/{p}/edit.html"), ctx.edit_html());
    plan.create(format!("templates/{p}/_form.html"), ctx.form_html());
    feature::plan_into(&mut plan, &ctx.routes());
    if nav {
        plan.insert(
            "templates/shared/_nav.html",
            "nav links",
            html::resource("nav link", &[("PATH_FN", p), ("LABEL", &n.human_plural)]),
        );
    }
    if spec.scope == Scope::Public {
        plan.insert(
            "src/controllers/meta.rs",
            "sitemap paths",
            format!("paths::{p}(),\n"),
        );
    }
    let t = format!("tests/app/{p}");
    plan.create(format!("{t}/mod.rs"), ctx.tests_mod());
    plan.create(format!("{t}/read_test.rs"), ctx.tests_read());
    plan.create(format!("{t}/write_test.rs"), ctx.tests_write());
    if spec.scope == Scope::User {
        plan.create(format!("{t}/access_test.rs"), ctx.tests_access());
    }
    plan.insert("tests/app/main.rs", "test mods", format!("mod {p};\n"));
    if spec.scope == Scope::User {
        tenancy::plan_into(info, &mut plan, &spec, flags);
    }
    plan.next
        .push("cargo run -q -- db migrate   # then prove down(): db rollback && db migrate".into());
    plan.next.push(
        "bin/tailwindcss -i assets/app.css -o static/app.css --minify   # the new pages' classes (bin/dev does it live)"
            .into(),
    );
    plan.next.push(format!(
        "write product/features/{p}.md (acceptance criteria + the STRIDE Security table) and cite its AC ids in tests/app/{p}/"
    ));
    plan.next.push(format!(
        "customize: src/models/{s}/ (validation limits, the label), templates/{p}/ (what each page shows); every `// APP:` line is a decision to make"
    ));
    plan.next.push(format!(
        "commit now (git add -A && git commit -m \"generate resource {p}\"), before you change anything: your edits are then a diff of their own"
    ));
    if spec.scope == Scope::User && !info.tenancy_suites() {
        plan.next.push(
            "AGENTS.md says TENANCY: none, and these records belong to users: set `TENANCY: per-user` (offrails-check then requires the tenancy suites, which are in)".into(),
        );
    }
    if spec.scope == Scope::Public {
        plan.next.push(format!(
            "SECURITY: {p} is --public (anyone can create, change and delete); add accounts and regenerate before it holds real data"
        ));
    }
    Ok(plan)
}

