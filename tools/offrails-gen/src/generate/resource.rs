#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn display_strings() {
        let f = Field::parse("price:money?").unwrap();
        assert_eq!(
            display(&f, "item"),
            "r.price_cents.as_ref().map(|v| item::money_to_string(*v)).unwrap_or_else(|| \"—\".to_owned())"
        );
        let f = Field::parse("price:money").unwrap();
        assert_eq!(display(&f, "item"), "item::money_to_string(r.price_cents)");
        let f = Field::parse("at:datetime").unwrap();
        assert_eq!(
            display(&f, "item"),
            "r.at.format(\"%Y-%m-%d %H:%M UTC\").to_string()"
        );
        let f = Field::parse("book:references").unwrap();
        assert_eq!(display(&f, "item"), "format!(\"Book #{}\", r.book_id)");
        let f = Field::parse("count:integer?").unwrap();
        assert_eq!(
            display(&f, "item"),
            "r.count.as_ref().map(|v| v.to_string()).unwrap_or_else(|| \"—\".to_owned())"
        );
    }

    #[test]
    fn routes_table_rows_line_up() {
        let rows = vec![
            ("GET".into(), "/posts".into(), "posts::index".into()),
            (
                "POST".into(),
                "/posts/{id}/delete".into(),
                "posts::destroy".into(),
            ),
        ];
        let t = routes_table(&rows, "User");
        assert!(t.starts_with("(\"GET\",  \"/posts\","));
        assert!(t.contains("Access::User),\n"));
    }
}
