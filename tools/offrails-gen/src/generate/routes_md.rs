//! The `ROUTES` table, read from `src/routes.rs` without compiling the app, and `docs/routes.md`
//! rewritten from it exactly as `cargo run -- routes` writes it (so generators keep it current
//! in milliseconds, and `offrails-check [routes]` stays green).

use std::path::Path;

use crate::util::{self, Result, rel};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Route {
    pub method: String,
    pub path: String,
    pub handler: String,
    pub access: String,
}

/// Every row of `pub const ROUTES` in `src/routes.rs`.
pub fn parse(routes_rs: &str) -> Vec<Route> {
    let mut out = Vec::new();
    let mut inside = false;
    for line in routes_rs.lines() {
        let t = line.trim();
        if t.starts_with("pub const ROUTES") {
            inside = true;
            continue;
        }
        if !inside {
            continue;
        }
        if t.starts_with("];") {
            break;
        }
        if !t.starts_with("(\"") {
            continue;
        }
        let quoted: Vec<&str> = t.split('"').collect();
        // ("GET", "/x", "h", Access::User),  →  ["(", "GET", ", ", "/x", ", ", "h", ", Access::User),"]
        if quoted.len() < 7 {
            continue;
        }
        let access = quoted[6]
            .split("Access::")
            .nth(1)
            .map(|a| a.trim_end_matches([')', ',', ' ']).to_ascii_lowercase())
            .unwrap_or_default();
        out.push(Route {
            method: quoted[1].to_owned(),
            path: quoted[3].to_owned(),
            handler: quoted[5].to_owned(),
            access,
        });
    }
    out
}

pub fn render(routes: &[Route]) -> String {
    let mut md = String::from(
        "# Routes\n\n<!-- Generated by `cargo run -- routes`. Do not edit. -->\n\n| Method | Path | Handler | Access |\n|--------|------|---------|--------|\n",
    );
    for r in routes {
        md.push_str(&format!(
            "| {} | `{}` | `{}` | {} |\n",
            r.method, r.path, r.handler, r.access
        ));
    }
    md
}

/// Rewrites `docs/routes.md` when `ROUTES` says something else. Returns whether it changed.
pub fn refresh(app: &Path) -> Result<bool> {
    let Ok(src) = std::fs::read_to_string(rel(app, "src/routes.rs")) else {
        return Ok(false);
    };
    let routes = parse(&src);
    if routes.is_empty() {
        return Ok(false);
    }
    let path = rel(app, "docs/routes.md");
    let md = render(&routes);
    let before = std::fs::read_to_string(&path).unwrap_or_default();
    if before.replace("\r\n", "\n") == md {
        return Ok(false);
    }
    util::write_text(&path, &md)?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_the_template_table_and_renders_what_main_rs_writes() {
        let src = "pub const ROUTES: &[(&str, &str, &str, Access)] = &[\n    (\"GET\",  \"/\",       \"home::index\",   Access::Public),\n    (\"POST\", \"/x/{id}\", \"x::update\",     Access::User),\n    // samples: routes table\n];\n";
        let r = parse(src);
        assert_eq!(r.len(), 2);
        assert_eq!(r[1].access, "user");
        assert_eq!(r[1].path, "/x/{id}");
        assert!(render(&r).contains("| POST | `/x/{id}` | `x::update` | user |\n"));
        let template = include_str!("../../../../template/app/src/routes.rs");
        let doc = include_str!("../../../../template/app/docs/routes.md");
        assert_eq!(render(&parse(template)), doc.replace("\r\n", "\n"));
    }
}
