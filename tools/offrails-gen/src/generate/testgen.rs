//! `generate test <request|model|job|unit> <name>`: a test file in the app's one test binary
//! (`tests/app/`), registered in `tests/app/main.rs`, with a first test to replace.

use super::Flags;
use super::app::AppInfo;
use super::names;
use super::plan::Plan;
use crate::util::{Fail, Result};

/// `generate test <kind> <name>`.
pub fn plan(info: &AppInfo, args: &[String], _flags: &Flags) -> Result<Plan> {
    let [kind, raw] = args else {
        return Err(Fail::usage(
            "generate test needs a kind and a name: generate test request checkout",
        ));
    };
    let name = names::snake(raw);
    if name.is_empty() || names::RUST_KEYWORDS.contains(&name.as_str()) {
        return Err(Fail::usage(format!("'{raw}' isn't a usable test name")));
    }
    let file = format!("{name}_test");
    let mut plan = Plan::new("test", &format!("{kind}:{name}"), args);
    let k = &info.krate;
    let body = match kind.as_str() {
        "request" => format!(
            "use axum::http::StatusCode;\nuse {k}::routes::paths;\n\nuse crate::support::TestApp;\n\n/// APP: cite the AC this proves (`/// AC-<feature>-<n>`).\n#[tokio::test]\nasync fn {name}_works() {{\n    let app = TestApp::new().await;\n    // APP: the request and what the page or redirect must show.\n    app.get(&paths::root()).await.assert_status(StatusCode::OK);\n}}\n"
        ),
        "model" => format!(
            "use crate::support::TestApp;\n\n/// APP: a model function against the database (both backends).\n#[tokio::test]\nasync fn {name}_works() {{\n    let app = TestApp::new().await;\n    let _db = app.db();\n    // APP: create through a factory, call the model fn, assert the rows.\n}}\n"
        ),
        "job" => format!(
            "use crate::support::TestApp;\n\n/// APP: perform the job (`app.perform_job(..)`), or enqueue and `app.drain_jobs()`.\n#[tokio::test]\nasync fn {name}_works() {{\n    let app = TestApp::new().await;\n    let _db = app.db();\n}}\n"
        ),
        "unit" => format!(
            "/// APP: a pure function of {k}.\n#[test]\nfn {name}_works() {{\n    // APP: assert_eq!(…);\n}}\n"
        ),
        other => {
            return Err(Fail::usage(format!(
                "test kind '{other}': request | model | job | unit"
            )));
        }
    };
    plan.create(
        format!("tests/app/{file}.rs"),
        format!(
            "//! {}. Generated by `{}`.\n\n{body}",
            names::human(&name),
            plan.command()
        ),
    );
    plan.insert("tests/app/main.rs", "test mods", format!("mod {file};\n"));
    plan.next.push(format!(
        "write the tests in tests/app/{file}.rs (testing guide: .offrails/guides/testing.md)"
    ));
    Ok(plan)
}
