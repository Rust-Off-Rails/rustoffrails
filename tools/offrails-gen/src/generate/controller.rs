//! `generate controller <name> [action…]` (`rails generate controller`): one handler per action
//! (each a GET page; `index` is `/<name>`, others `/<name>/<action>`), its page struct and
//! template, the routes (router, `paths::`, `ROUTES`, docs/routes.md) and request tests.
//! With accounts the pages need a signed-in user (`--public`: anyone).

use super::Flags;
use super::app::AppInfo;
use super::names::{self, Names};
use super::plan::Plan;
use super::resource::{check_free, routes_table};
use crate::util::{Fail, Result};

/// One page action: its URL, `paths::` helper, page struct and template.
pub struct Action {
    pub name: String,
    pub url: String,
    pub path_fn: String,
    pub view: String,
    pub template: String,
}

pub fn actions(n: &Names, raw: &[String]) -> Result<Vec<Action>> {
    let mut list: Vec<String> = raw.iter().map(|a| names::snake(a)).collect();
    if list.is_empty() {
        list.push("index".into());
    }
    let mut out: Vec<Action> = Vec::new();
    for a in list {
        if a.is_empty() || names::RUST_KEYWORDS.contains(&a.as_str()) || a == "new" {
            return Err(Fail::usage(format!(
                "action '{a}' can't be a handler name (a Rust keyword, or `new`); pick another"
            )));
        }
        if out.iter().any(|o| o.name == a) {
            return Err(Fail::usage(format!("action '{a}' is given twice")));
        }
        let (url, path_fn) = if a == "index" {
            (format!("/{}", n.kebab), n.singular.clone())
        } else {
            (
                format!("/{}/{}", n.kebab, a.replace('_', "-")),
                format!("{}_{a}", n.singular),
            )
        };
        out.push(Action {
            view: format!("{}{}", n.model, names::camel(&a)),
            template: format!("{}/{a}.html", n.singular),
            url,
            path_fn,
            name: a,
        });
    }
    Ok(out)
}

/// `generate controller <name> [action…]`.
pub fn plan(info: &AppInfo, args: &[String], flags: &Flags) -> Result<Plan> {
    info.require_htmx("generate controller")?;
    let n = Names::plain(&args[0])?;
    for taken in [
        "application",
        "auth",
        "dev",
        "errors",
        "health",
        "home",
        "meta",
        "migrations",
        "theme",
        "pages",
    ] {
        if n.singular == taken {
            return Err(Fail::usage(format!(
                "a controller named '{taken}' already exists in every app (or `generate page` owns it); pick another name"
            )));
        }
    }
    let mut plan = Plan::new("controller", &n.singular, args);
    let acts = actions(&n, &args[1..])?;
    let user = match flags.recorded("scope").as_deref() {
        Some(s) => s == "user",
        None => info.auth && !flags.public,
    };
    plan.option("scope", if user { "user" } else { "public" });
    if flags.recorded("scope").is_none() {
        check_free(
            info,
            &acts.iter().map(|a| a.path_fn.clone()).collect::<Vec<_>>(),
            &acts.iter().map(|a| a.url.clone()).collect::<Vec<_>>(),
        )?;
    }
    let c = &n.singular;
    let cmd = plan.command();
    let k = &info.krate;

    let mut ctl = format!(
        "//! {}: {}. Generated by `{cmd}`.\n//! APP: what these pages are for (product/features/{c}.md); load their data in each handler.\n\nuse axum::response::{{IntoResponse, Response}};\n\n",
        n.human,
        acts.iter()
            .map(|a| a.name.as_str())
            .collect::<Vec<_>>()
            .join(", ")
    );
    if user {
        ctl.push_str("use crate::controllers::auth::RequireUser;\n");
    }
    let mut view_names: Vec<&str> = acts.iter().map(|a| a.view.as_str()).collect();
    view_names.sort_unstable();
    let imported = if view_names.len() == 1 {
        view_names[0].to_owned()
    } else {
        format!("{{{}}}", view_names.join(", "))
    };
    ctl.push_str(&format!(
        "use crate::error::AppError;\nuse crate::views::{{self, Ctx, {c}::{imported}}};\n\n"
    ));
    let mut views = format!(
        "//! Page structs for {}. Generated by `{cmd}`.\n\nuse askama::Template;\n\nuse super::Ctx;\n// The layout links with `paths::`.\nuse crate::routes::paths;\n\n",
        n.lower
    );
    let mut tests = format!(
        "//! {} (src/controllers/{c}.rs). Generated by `{cmd}`.\n//! APP: assert what each page shows, citing its AC (`/// AC-{c}-1`).\n\nuse {k}::routes::paths;\n\n{}use crate::support::TestApp;\n\n",
        n.human,
        if user { "use crate::factories;\n" } else { "" }
    );
    let mut router = format!(
        "// {} (cargo offrails generate controller {c})\napp = app\n",
        n.human
    );
    let mut paths = String::new();
    let mut rows = Vec::new();
    for a in &acts {
        let title = if a.name == "index" {
            n.human.clone()
        } else {
            format!("{} {}", n.human, a.name.replace('_', " "))
        };
        let auth = if user {
            "    RequireUser(_user): RequireUser, // unscoped: reads nothing yet (APP: scope what it loads with the user)\n"
        } else {
            ""
        };
        ctl.push_str(&format!(
            "/// `GET {url}`\n#[tracing::instrument(skip_all)]\npub async fn {name}(\n    ctx: Ctx,\n{auth}) -> Result<Response, AppError> {{\n    Ok(views::render({view} {{\n        ctx: ctx.titled(\"{title}\"){ni},\n    }})?\n    .into_response())\n}}\n\n",
            url = a.url,
            name = a.name,
            view = a.view,
            ni = if user { ".noindex()" } else { "" }
        ));
        views.push_str(&format!(
            "/// `GET {}`\n#[derive(Template)]\n#[template(path = \"{}\")]\npub struct {} {{\n    pub ctx: Ctx,\n}}\n\n",
            a.url, a.template, a.view
        ));
        plan.create(
            format!("templates/{}", a.template),
            format!(
                "{{% extends \"layouts/application.html\" %}}\n{{% block content %}}\n<h1 class=\"text-3xl font-semibold tracking-tight\">{title}</h1>\n<p class=\"mt-4 text-gray-700 dark:text-gray-300\">APP: what this page shows (templates/{}).</p>\n{{% endblock %}}\n",
                a.template
            ),
        );
        let setup = if user {
            "    let me = factories::user(app.db(), \"me@example.com\").await;\n    app.sign_in_as(&me).await;\n"
        } else {
            ""
        };
        tests.push_str(&format!(
            "#[tokio::test]\nasync fn {name}_renders() {{\n    let app = TestApp::new().await;\n{setup}    app.get(&paths::{pf}())\n        .await\n        .assert_ok()\n        .assert_text(\"{title}\");\n}}\n\n",
            name = a.name,
            pf = a.path_fn
        ));
        if user {
            tests.push_str(&format!(
                "/// SECURITY: signed out, the page sends you to sign in.\n#[tokio::test]\nasync fn {name}_needs_a_signed_in_user() {{\n    let app = TestApp::new().await;\n    app.get(&paths::{pf}())\n        .await\n        .assert_redirect_to(&paths::new_session());\n}}\n\n",
                name = a.name,
                pf = a.path_fn
            ));
        }
        router.push_str(&format!(
            "    .route(\"{}\", get(crate::controllers::{c}::{}))\n",
            a.url, a.name
        ));
        paths.push_str(&format!(
            "pub fn {}() -> String {{\n    \"{}\".into()\n}}\n",
            a.path_fn, a.url
        ));
        rows.push(("GET".to_owned(), a.url.clone(), format!("{c}::{}", a.name)));
    }
    let router = format!("{};\n\n", router.trim_end());
    plan.create(
        format!("src/controllers/{c}.rs"),
        ctl.trim_end().to_owned() + "\n",
    );
    plan.insert(
        "src/controllers/mod.rs",
        "controller mods",
        format!("pub mod {c};\n"),
    );
    plan.create(
        format!("src/views/{c}.rs"),
        views.trim_end().to_owned() + "\n",
    );
    plan.insert("src/views/mod.rs", "view mods", format!("pub mod {c};\n"));
    plan.insert("src/routes.rs", "routes", router);
    plan.insert("src/routes.rs", "paths", paths);
    plan.insert(
        "src/routes.rs",
        "routes table",
        routes_table(&rows, if user { "User" } else { "Public" }),
    );
    let nav = flags.nav || flags.recorded("nav").as_deref() == Some("yes");
    plan.option("nav", if nav { "yes" } else { "no" });
    if nav {
        plan.insert(
            "templates/shared/_nav.html",
            "nav links",
            nav_link(&acts[0].path_fn, &n.human),
        );
    }
    plan.create(
        format!("tests/app/{c}_test.rs"),
        tests.trim_end().to_owned() + "\n",
    );
    plan.insert("tests/app/main.rs", "test mods", format!("mod {c}_test;\n"));
    plan.next.push(format!(
        "fill each page: load its data in src/controllers/{c}.rs (scoped to the user), add fields to its struct in src/views/{c}.rs, write templates/{c}/"
    ));
    plan.next.push(
        "bin/tailwindcss -i assets/app.css -o static/app.css --minify   # new classes (bin/dev does it live)".into(),
    );
    Ok(plan)
}

/// A link in the main nav (`templates/shared/_nav.html`; full paths: partials resolve names in
/// each including struct's module).
pub fn nav_link(path_fn: &str, label: &str) -> String {
    format!(
        "<a href=\"{{{{ crate::routes::paths::{path_fn}() }}}}\" class=\"text-gray-700 dark:text-gray-300 hover:text-gray-900 dark:hover:text-gray-100\">{label}</a>\n"
    )
}
