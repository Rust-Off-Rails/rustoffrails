//! `generate job <Name> [arg:type…] [--queue q]` (`rails generate job`): a `Worker` with id-only
//! args in `src/jobs/<name>.rs`, registered in `dispatch`, `worker_config` and `WORKERS`, and a
//! test (perform, enqueue + drain, registered). Needs the jobs part. Spec: guides/jobs.md.

use super::Flags;
use super::app::AppInfo;
use super::fields::{self, Kind};
use super::names;
use super::plan::{Anchor, Plan};
use crate::util::{Fail, Result};

/// `NotifyPostPublished`, `notify_post_published_job` → `notify_post_published`.
pub fn job_name(raw: &str) -> Result<String> {
    let s = names::snake(raw);
    let s = s.strip_suffix("_job").unwrap_or(&s).to_owned();
    if s.is_empty() || names::RUST_KEYWORDS.contains(&s.as_str()) {
        return Err(Fail::usage(format!("'{raw}' isn't a usable job name")));
    }
    Ok(s)
}

/// `generate job <Name> [arg:type…]`.
pub fn plan(info: &AppInfo, args: &[String], flags: &Flags) -> Result<Plan> {
    if !info.jobs {
        return Err(Fail::usage(
            "generate job needs the job queue: cargo offrails add jobs (and jobs-dashboard for /admin/jobs)",
        ));
    }
    let name = job_name(&args[0])?;
    let mut plan = Plan::new("job", &name, args);
    let ty = format!("{}Job", names::camel(&name));
    let args_f = fields::parse_all(&args[1..], &[])?;
    let mut fields_src = String::new();
    let mut sample = String::new();
    for f in &args_f {
        let (rust, value) = match f.kind {
            Kind::BigInt | Kind::References { .. } => ("i64", "1".to_owned()),
            Kind::Integer => ("i32", "1".to_owned()),
            Kind::String => ("String", "\"example\".into()".to_owned()),
            Kind::Boolean => ("bool", "true".to_owned()),
            _ => {
                return Err(Fail::usage(format!(
                    "job arg {}: args are ids and small values (bigint, integer, string, boolean, references); load records in perform",
                    f.spec()
                )));
            }
        };
        let rust = if f.nullable {
            format!("Option<{rust}>")
        } else {
            rust.to_owned()
        };
        let value = if f.nullable {
            format!("Some({value})")
        } else {
            value
        };
        fields_src.push_str(&format!("    pub {}: {rust},\n", f.column()));
        sample.push_str(&format!("        {}: {value},\n", f.column()));
    }
    if fields_src.is_empty() {
        fields_src.push_str("    // APP: the args: ids, never records or secrets (they are stored and shown on /admin/jobs).\n");
    } else {
        fields_src.insert_str(
            0,
            "    // WHY: ids, never records or secrets: args are stored and shown on /admin/jobs.\n",
        );
    }
    let queue = flags
        .recorded("queue")
        .or_else(|| flags.value("queue"))
        .unwrap_or_else(|| "default".into());
    if !queue
        .chars()
        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
    {
        return Err(Fail::usage(format!(
            "--queue {queue}: lowercase letters, digits and _"
        )));
    }
    plan.option("queue", queue.clone());
    let queue_line = if queue == "default" {
        String::new()
    } else {
        format!("    const QUEUE: &'static str = \"{queue}\";\n")
    };
    let cmd = plan.command();
    let k = &info.krate;
    plan.create(
        format!("src/jobs/{name}.rs"),
        format!(
            "//! `{ty}`. Generated by `{cmd}`.\n//! APP: what it does, who enqueues it (in the same transaction as the change: models.md#side-effects-no-callbacks).\n\nuse serde::{{Deserialize, Serialize}};\n\nuse crate::{{\n    jobs::{{JobInfo, Outcome, Worker}},\n    state::AppState,\n}};\n\n#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]\npub struct {ty} {{\n{fields_src}}}\n\nimpl Worker for {ty} {{\n    /// Permanent: queued rows and the dashboard's history name it.\n    const NAME: &'static str = \"{name}\";\n{queue_line}    /// APP: size to the work (20 suits syncs; mail wants ~5).\n    const MAX_ATTEMPTS: i32 = 5;\n\n    #[tracing::instrument(skip_all)]\n    async fn perform(self, _job: &JobInfo, _state: &AppState) -> anyhow::Result<Outcome> {{\n        // APP: the work. Load records by id (`<model>::find_system`); a record that's gone is\n        // `Ok(Outcome::Cancel(..))`, a transient failure an `Err` (retried with backoff).\n        // It may run twice: make it idempotent (guides/jobs.md#rules).\n        Ok(Outcome::Done)\n    }}\n}}\n"
        ),
    );
    let jobs = "src/jobs/mod.rs";
    plan.insert_at(
        jobs,
        Anchor::AfterLast("pub mod ".into()),
        format!("pub mod {name};\n"),
    );
    plan.insert_at(
        jobs,
        Anchor::Before {
            after: None,
            pattern: "pub use crate::kernel::jobs::{".into(),
        },
        format!("pub use {name}::{ty};\n"),
    );
    plan.insert_at(
        jobs,
        Anchor::Before {
            after: Some("pub async fn dispatch".into()),
            pattern: "other => Ok(Outcome::Discard(".into(),
        },
        format!("{ty}::NAME => run::<{ty}>(&state, args, &job).await,\n"),
    );
    plan.insert_at(
        jobs,
        Anchor::Before {
            after: Some("pub fn worker_config".into()),
            pattern: "_ => WorkerConfig::default()".into(),
        },
        format!("{ty}::NAME => config::<{ty}>(),\n"),
    );
    plan.insert_at(
        jobs,
        Anchor::Before {
            after: Some("pub const WORKERS".into()),
            pattern: "];".into(),
        },
        format!("{ty}::NAME,\n"),
    );
    plan.create(
        format!("tests/app/{name}_job_test.rs"),
        format!(
            "//! `{ty}` (src/jobs/{name}.rs). Generated by `{cmd}`.\n//! APP: assert its effect (a row changed, an email sent), its idempotency (run twice, one\n//! effect) and the record-gone path (`Outcome::Cancel`) (test-standards.md#what-each-suite-contains).\n\nuse {k}::jobs::{{self, Outcome, WORKERS, Worker, {ty}}};\n\nuse crate::support::TestApp;\n\nfn job() -> {ty} {{\n    {ty} {{\n{sample}    }}\n}}\n\n#[test]\nfn it_is_registered_so_queued_rows_run() {{\n    assert!(WORKERS.contains(&{ty}::NAME));\n}}\n\n#[tokio::test]\nasync fn perform_finishes() {{\n    let app = TestApp::new().await;\n    let outcome = app.perform_job(job()).await.unwrap();\n    assert!(matches!(outcome, Outcome::Done), \"{{outcome:?}}\");\n}}\n\n#[tokio::test]\nasync fn an_enqueued_job_runs_when_the_queue_drains() {{\n    let app = TestApp::new().await;\n    jobs::enqueue(app.db(), job()).await.unwrap();\n    app.assert_enqueued::<{ty}>(|j| *j == job()).await;\n    app.drain_jobs().await;\n    app.refute_enqueued::<{ty}>().await;\n}}\n"
        ),
    );
    plan.insert(
        "tests/app/main.rs",
        "test mods",
        format!("mod {name}_job_test;\n"),
    );
    plan.next.push(format!(
        "write perform() in src/jobs/{name}.rs, and enqueue it from the model fn that owns the change: jobs::enqueue(&txn, {ty} {{ … }})"
    ));
    let queues = info.read("src/config.rs").unwrap_or_default();
    if queue != "default" && !queues.contains(&format!("{queue}:")) {
        plan.next.push(format!(
            "queue `{queue}` isn't in JobsConfig::DEFAULT_QUEUES (src/config.rs) or APP_QUEUES: add `{queue}:5` to both and to .env.example, or its jobs wait forever"
        ));
    }
    plan.next.push(
        "recurring? add a `Recurring { key, cron, job }` to SCHEDULE in src/jobs/recurring.rs (UTC)".into(),
    );
    Ok(plan)
}
