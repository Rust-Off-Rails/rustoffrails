//! `generate mailer <name> [action…]` (`rails generate mailer`): pure functions that render an
//! `Email` (HTML + text templates on the shared mail layout, absolute links), a preview per
//! action in the dev mailbox, and tests. Needs the mailer part. Spec: guides/mailers.md.

use super::Flags;
use super::app::AppInfo;
use super::names;
use super::plan::Plan;
use crate::util::{Fail, Result};

/// `PostMailer`, `post` → `post_mailer`.
pub fn mailer_name(raw: &str) -> Result<String> {
    let s = names::snake(raw);
    let base = s.strip_suffix("_mailer").unwrap_or(&s);
    if base.is_empty() || names::RUST_KEYWORDS.contains(&base) {
        return Err(Fail::usage(format!("'{raw}' isn't a usable mailer name")));
    }
    Ok(format!("{base}_mailer"))
}

/// `generate mailer <name> [action…]`.
pub fn plan(info: &AppInfo, args: &[String], _flags: &Flags) -> Result<Plan> {
    if !info.mailer {
        return Err(Fail::usage(
            "generate mailer needs the mailer: cargo offrails add mailer dev-mailbox",
        ));
    }
    let m = mailer_name(&args[0])?;
    let mut plan = Plan::new("mailer", &m, args);
    let mut actions: Vec<String> = args[1..].iter().map(|a| names::snake(a)).collect();
    if actions.is_empty() {
        actions.push("notice".into());
    }
    for a in &actions {
        if a.is_empty() || names::RUST_KEYWORDS.contains(&a.as_str()) {
            return Err(Fail::usage(format!(
                "'{a}' isn't a usable mailer action name"
            )));
        }
    }
    let cmd = plan.command();
    let k = &info.krate;
    let human = names::human(m.trim_end_matches("_mailer"));
    let mut src = format!(
        "//! `{}`. Generated by `{cmd}`.\n//! Pure: data in, rendered `Email` out, no database (callers load the data). Links are absolute.\n//! Send from a job: `state.mailer.deliver(email)` (guides/mailers.md#delivering); a link with a\n//! token is minted inside that job, never put in its args.\n\nuse askama::Template;\n\nuse crate::config::Config;\nuse crate::error::AppError;\nuse crate::kernel::mailer::Email;\nuse crate::routes::paths;\n\n",
        names::camel(&m)
    );
    let mut tests = format!(
        "//! `{m}` (src/mailers/{m}.rs). Generated by `{cmd}`.\n//! APP: assert the recipient, subject, a key line of the body and that its links work.\n\nuse {k}::mailers::{m};\n\nuse crate::support::TestApp;\n\n"
    );
    for a in &actions {
        let camel = names::camel(a);
        let subject = format!("{human}: {}", a.replace('_', " "));
        src.push_str(&format!(
            "#[derive(Template)]\n#[template(path = \"mailers/{m}/{a}.html\")]\nstruct {camel}Html<'a> {{\n    app_name: &'a str,\n    url: &'a str,\n}}\n\n#[derive(Template)]\n#[template(path = \"mailers/{m}/{a}.txt\")]\nstruct {camel}Text<'a> {{\n    app_name: &'a str,\n    url: &'a str,\n}}\n\n/// \"{subject}\". APP: take what it's about (`post: &post::Model`) and say it.\npub fn {a}(config: &Config, to: &str) -> Result<Email, AppError> {{\n    // INVARIANT: links are absolute (config.app_url + a paths:: helper).\n    let url = format!(\"{{}}{{}}\", config.app_url, paths::root());\n    let app_name = crate::config::APP_NAME;\n    Ok(Email::new(\n        to,\n        format!(\"{subject} ({{app_name}})\"),\n        {camel}Html {{\n            app_name,\n            url: &url,\n        }}\n        .render()?,\n        {camel}Text {{\n            app_name,\n            url: &url,\n        }}\n        .render()?,\n    ))\n}}\n\n"
        ));
        plan.create(
            format!("templates/mailers/{m}/{a}.html"),
            format!(
                "{{% extends \"mailers/layout.html\" %}}\n{{% block title %}}{subject}{{% endblock %}}\n{{% block content %}}\n<h1 style=\"margin:0 0 16px;font-size:20px;line-height:1.3;\">{subject}</h1>\n<p style=\"margin:0 0 16px;\">APP: what this email says (templates/mailers/{m}/{a}.html; the text part says the same).</p>\n<p style=\"margin:0 0 24px;\">\n  <a href=\"{{{{ url }}}}\" style=\"display:inline-block;background:#4f46e5;color:#ffffff;text-decoration:none;font-weight:600;padding:10px 18px;border-radius:6px;\">Open {{{{ app_name }}}}</a>\n</p>\n<p class=\"mail-muted\" style=\"margin:0;color:#6b7280;font-size:13px;\">Or paste this link into your browser: <a href=\"{{{{ url }}}}\" class=\"mail-link\" style=\"color:#4338ca;\">{{{{ url }}}}</a></p>\n{{% endblock %}}\n"
            ),
        );
        plan.create(
            format!("templates/mailers/{m}/{a}.txt"),
            format!(
                "{subject}\n\nAPP: what this email says (templates/mailers/{m}/{a}.txt).\n\nOpen {{{{ app_name }}}}: {{{{ url }}}}\n"
            ),
        );
        plan.insert(
            "src/mailers/previews.rs",
            "previews",
            format!(
                "Preview {{\n    name: \"{m}/{a}\",\n    build: |s| Box::pin(async {{ crate::mailers::{m}::{a}(&s.config, \"ada@example.com\") }}),\n}},\n"
            ),
        );
        tests.push_str(&format!(
            "#[tokio::test]\nasync fn {a}_has_both_parts_and_absolute_links() {{\n    let app = TestApp::new().await;\n    let email = {m}::{a}(&app.state.config, \"ada@example.com\").unwrap();\n    assert_eq!(email.to, \"ada@example.com\");\n    assert!(email.subject.starts_with(\"{subject}\"), \"{{}}\", email.subject);\n    let link = format!(\"{{}}/\", app.state.config.app_url);\n    assert!(email.html.contains(&link), \"html part links to the app\");\n    assert!(email.text.contains(&link), \"text part links to the app\");\n}}\n\n#[tokio::test]\nasync fn {a}_is_delivered() {{\n    let app = TestApp::new().await;\n    let email = {m}::{a}(&app.state.config, \"ada@example.com\").unwrap();\n    app.state.mailer.deliver(email).await.unwrap();\n    let sent = app.last_email_to(\"ada@example.com\").expect(\"sent\");\n    assert!(sent.subject.starts_with(\"{subject}\"));\n}}\n\n"
        ));
    }
    plan.create(
        format!("src/mailers/{m}.rs"),
        src.trim_end().to_owned() + "\n",
    );
    plan.insert(
        "src/mailers/mod.rs",
        "mailer mods",
        format!("pub mod {m};\n"),
    );
    plan.create(
        format!("tests/app/{m}_test.rs"),
        tests.trim_end().to_owned() + "\n",
    );
    plan.insert("tests/app/main.rs", "test mods", format!("mod {m}_test;\n"));
    plan.next.push(format!(
        "give each action its data (src/mailers/{m}.rs) and its words (templates/mailers/{m}/); send it from a job: `cargo offrails g job …` then `state.mailer.deliver(email)` in perform"
    ));
    if info.dev_mailbox {
        plan.next.push(format!(
            "see it: /dev/mailbox/previews ({m}/{}), real ones at /dev/mailbox",
            actions[0]
        ));
    }
    Ok(plan)
}
