#!/usr/bin/env bash
# PreToolUse (Edit|Write|MultiEdit): block edits to files that must never be hand-edited.
source "$(dirname "$0")/lib.sh"
in_offrails_app || exit 0
require_jq

raw="$(json_get '.tool_input.file_path // .tool_input.notebook_path')"
[ -n "$raw" ] || exit 0
file="$(rel_path_canon "$raw")"
# macOS volumes are usually case-insensitive: match the guarded prefixes case-insensitively.
lower="$(printf '%s' "$file" | tr 'A-Z' 'a-z')"

case "$lower" in
  .offrails/*)
    echo "Blocked: .offrails/ is the vendored framework and is read-only. To deviate, record it in docs/decisions.md and tell the human. To update it, use /offrails:upgrade." >&2
    exit 2 ;;
  web/src/types/*)
    echo "Blocked: web/src/types/ is generated by ts-rs. Change the Rust type (#[derive(TS)]) and run cargo nextest run to re-export." >&2
    exit 2 ;;
  migration/src/m[0-9]*.rs)
    # Committed migrations are append-only: existing databases never re-run an edited one.
    if git -C "$PROJECT_DIR" cat-file -e "HEAD:$file" 2>/dev/null; then
      echo "Blocked: $file is already committed, and committed migrations are append-only (guides/migrations.md rule 1). Databases that ran it will never see your edit. Generate a new migration (sea-orm-cli migrate generate …) that alters the schema instead." >&2
      exit 2
    fi ;;
esac
exit 0
